        <h2>1. Cancellation Window</h2>

        <p>
            Users may cancel meal bookings, pantry orders, or QSR orders only before the configured
            cutoff time defined by the organization or cafeteria administrator.
        </p>

        <h2>2. After Cutoff Time</h2>

        <div class="highlight-box">
            <strong>After the cutoff time</strong>

            <p>
                Orders become non-cancellable and may proceed for preparation.
            </p>
        </div>

        <h2>3. Cancellation Process</h2>

        <p>
            Eligible cancellations can be performed directly through the JOI Foods application.
        </p>

        <h2>4. Refund on Cancellation</h2>

        <p>
