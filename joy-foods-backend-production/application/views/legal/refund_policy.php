        <h2 style="border-bottom: 2px solid #1e3a8a;">Refund Policy</h2>

        <h2>1. Scope</h2>

        <p>
            This Refund Policy applies to meal bookings, pantry orders, and QSR orders placed through
            the JOI Foods platform.
        </p>

        <h2>2. Refund Eligibility</h2>

        <p>
            Refunds are provided only in the user's JOI Foods wallet and only when the employee is
            eligible under the organization's meal and cafeteria policies.
        </p>

        <p>Refunds may be issued in the following situations:</p>

        <ul>
            <li>Order cancelled before the applicable cutoff time.</li>
            <li>Order could not be fulfilled due to operational issues.</li>
            <li>Duplicate payment or duplicate order detected and verified.</li>
            <li>Any other case approved by the organization or cafeteria administrator.</li>
        </ul>

        <h2>3. Refund Method</h2>

        <div class="highlight-box">
            <strong>Important</strong>

            <p>
                All approved refunds are credited only to the JOI Foods wallet associated with the user account.
            </p>

            <p>
                No cash refunds, bank transfers, UPI refunds, or card reversals are processed through the platform.
            </p>
        </div>

        <h2>4. Non-Refundable Cases</h2>

        <p>Refunds will generally not be provided for:</p>

        <ul>
            <li>Orders cancelled after the cutoff time.</li>
            <li>Meals not consumed after successful preparation.</li>
            <li>Incorrect selection made by the user.</li>
            <li>Orders marked as delivered/prepared according to cafeteria records.</li>
            <li>Violations of organizational cafeteria policies.</li>
        </ul>

        <h2>5. Refund Processing Time</h2>

        <p>
            Approved wallet refunds are typically processed within 1–7 business days, subject to
            organizational approval workflows.
        </p>

